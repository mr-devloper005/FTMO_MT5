"""Build the pinned Windows lock file from the top-level requirements, verifying that every
package has a prebuilt win_amd64 / CPython 3.12 wheel (nothing to compile on the PC).

    python deploy/windows/lock_requirements.py [--wheel-dir DIR]

Run it on any OS (it uses ``pip download --platform win_amd64``). The downloaded wheels can be
copied to the Windows PC as an offline package source: ``pip install --no-index --find-links DIR``.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
IN = HERE / "requirements-research.in"
LOCK = HERE / "requirements-research.lock.txt"
WHEEL = re.compile(r"^(?P<name>[A-Za-z0-9_.]+?)-(?P<version>[0-9][^-]*)-.+\.whl$")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_lines(wheel_names) -> list:
    pins = {}
    for w in wheel_names:
        m = WHEEL.match(w)
        if not m:
            raise ValueError(f"not a wheel file name: {w}")
        pins[canonical(m["name"])] = m["version"]
    return [f"{n}=={v}" for n, v in sorted(pins.items())]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wheel-dir", type=Path)
    a = ap.parse_args()
    wd = a.wheel_dir or Path(tempfile.mkdtemp(prefix="ftmo-wheels-win-"))
    wd.mkdir(parents=True, exist_ok=True)
    cmd = [sys.executable, "-m", "pip", "download", "-r", str(IN), "--dest", str(wd), "--platform", "win_amd64",
           "--python-version", "3.12", "--implementation", "cp", "--only-binary=:all:", "--quiet"]
    r = subprocess.run(cmd)
    if r.returncode:
        print("A package has no Windows wheel (see pip output above).", file=sys.stderr)
        return r.returncode
    lines = lock_lines(p.name for p in wd.glob("*.whl"))
    LOCK.write_text("# GENERATED by deploy/windows/lock_requirements.py from requirements-research.in.\n"
                    "# Every pin below has a prebuilt win_amd64 / CPython 3.12 wheel (verified by pip download).\n"
                    + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)} pins -> {LOCK}\nwheels in {wd}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
