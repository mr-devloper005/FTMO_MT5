class BaseEvent(BaseModel):
    """Base class for all domain events.

    All events are immutable and include correlation tracking
    and timestamp for audit trail.
    """

    model_config = ConfigDict(frozen=True)

    event_id: UUID = Field(default_factory=uuid4, description="Unique event identifier.")
    timestamp: datetime = Field(..., description="Event timestamp (UTC, timezone-aware).")
    correlation_id: UUID = Field(..., description="Correlation ID for request tracing.")


class SignalGenerated(BaseEvent):
    """Event: A new trading signal was generated.

    Published when a strategy produces a trading signal that
    is forwarded for risk checking and execution.
    """

    signal: TradingSignal = Field(..., description="The generated trading signal.")


class RiskChecked(BaseEvent):
    """Event: A trade request was checked against risk limits.

    Published after risk validation, indicating whether the
    trade was approved and what risk state was active.
    """

    approved: bool = Field(..., description="True if trade passed risk checks.")
    risk_state: RiskState = Field(..., description="System risk state at check time.")
    reason: str = Field(..., description="Explanation of approval/rejection decision.")


class OrderSubmitted(BaseEvent):
    """Event: A trade request was submitted to MT5.

    Published when an order is sent to the broker, before
    confirmation of execution.
    """

    trade_request: TradeRequest = Field(..., description="The submitted trade request.")
    submission_time: datetime = Field(..., description="Submission timestamp (UTC, timezone-aware).")


class OrderFilled(BaseEvent):
    """Event: An order was filled.

    Published when MT5 confirms execution with fill details.
    May represent partial or full fill.
    """

    deal_ticket: int = Field(..., ge=0, description="MT5 deal ticket number.")
    fill_price: Decimal = Field(..., gt=Decimal("0"), description="Actual fill price.")
    slippage: Decimal = Field(..., description="Price difference from requested to fill price.")
    volume_filled: Decimal = Field(..., gt=Decimal("0"), description="Volume actually filled (lots).")

    @field_validator("fill_price", "slippage", "volume_filled", mode="before")
    @classmethod
    def convert_to_decimal(cls, v: Any) -> Decimal:
        """Ensure fill metrics are Decimal."""
        if isinstance(v, Decimal):
            return v
        return Decimal(str(v))


class OrderRejected(BaseEvent):
    """Event: An order submission was rejected.

    Published when MT5 rejects an order before execution,
    with the specific return code and reason.
    """

    retcode: int = Field(..., ge=0, description="MT5 return code.")
    reason: str = Field(..., description="Human-readable rejection reason.")


class PositionClosed(BaseEvent):
    """Event: A position was closed.

    Published when an open position is fully exited,
    with final profit/loss and close price.
    """

    symbol: str = Field(..., min_length=1, max_length=10, description="Position symbol.")
    profit: Decimal = Field(..., description="Realized profit/loss.")
    close_price: Decimal = Field(..., gt=Decimal("0"), description="Close price.")

    @field_validator("profit", "close_price", mode="before")
    @classmethod
    def convert_to_decimal(cls, v: Any) -> Decimal:
        """Ensure financial amounts are Decimal."""
        if isinstance(v, Decimal):
            return v
        return Decimal(str(v))


class RiskStateChanged(BaseEvent):
    """Event: The system risk state changed.

    Published when risk management transitions to a different
    operational state (NORMAL -> CAUTION -> RISK_OFF -> HALT).
    """

    old_state: RiskState = Field(..., description="Previous risk state.")
    new_state: RiskState = Field(..., description="New risk state.")
    trigger: str = Field(..., description="Trigger reason for state change.")


class CircuitBreakerTriggered(BaseEvent):
    """Event: Circuit breaker was activated.

    Published when the system detects unacceptable risk and
    triggers emergency shutdown sequence.
    """

    reason: str = Field(..., description="Reason for circuit breaker trigger.")
    positions_to_close: int = Field(
        ...,
        ge=0,
        description="Number of positions scheduled for closure.",
    )


