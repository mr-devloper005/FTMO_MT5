class SystemConfig(BaseModel):
    """System-level configuration for MT5 connection and operations.

    Contains credentials, trading symbols, logging, and monitoring
    configuration for the automated trading system.
    """

    model_config = ConfigDict(validate_assignment=True, validate_default=True)

    model_config = ConfigDict(frozen=True)

    mt5_login: int = Field(..., ge=0, description="MT5 account login number.")
    mt5_server: str = Field(..., min_length=1, description="MT5 server name.")
    mt5_password: str = Field(..., description="MT5 password (should be encrypted in practice).")
    symbols: list[str] = Field(
        ...,
        min_length=1,
        description="List of trading symbols for this system.",
    )
    tick_interval_ms: int = Field(
        default=100,
        ge=10,
        description="Market data tick processing interval (milliseconds).",
    )
    heartbeat_interval_s: int = Field(
        default=5,
        ge=1,
        description="Health check heartbeat interval (seconds).",
    )
    max_agent_restarts: int = Field(
        default=3,
        ge=0,
        description="Maximum allowed consecutive agent restarts.",
    )
    otel_endpoint: Optional[str] = Field(
        default=None,
        description="OpenTelemetry collector endpoint for tracing.",
    )
    log_level: str = Field(
        default="INFO",
        pattern="^(DEBUG|INFO|WARNING|ERROR|CRITICAL)$",
        description="Logging level.",
    )

    @field_validator("symbols")
    @classmethod
    def validate_symbols(cls, v: list[str]) -> list[str]:
        """Validate symbol format."""
        if not v:
            raise ValueError("At least one symbol required")
        for symbol in v:
            if not (1 <= len(symbol) <= 10):
                raise ValueError(f"Invalid symbol length: {symbol}")
        return v
