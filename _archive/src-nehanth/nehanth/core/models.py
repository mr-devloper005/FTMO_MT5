# ============================================================================
# Enums
# ============================================================================


class OrderAction(str, Enum):
    """Enumeration of trading actions."""

    BUY = "BUY"
    """Open a long position."""

    SELL = "SELL"
    """Open a short position."""

    CLOSE_LONG = "CLOSE_LONG"
    """Close an existing long position."""

    CLOSE_SHORT = "CLOSE_SHORT"
    """Close an existing short position."""

    CLOSE_ALL = "CLOSE_ALL"
    """Close all open positions."""


class OrderType(str, Enum):
    """MT5 order types."""

    MARKET = "MARKET"
    """Market order - execute at current price."""

    LIMIT = "LIMIT"
    """Limit order - execute at or better than specified price."""

    STOP = "STOP"
    """Stop order - execute when price reaches trigger level."""

    STOP_LIMIT = "STOP_LIMIT"
    """Stop-limit order - trigger at stop level, fill at limit."""


class FillPolicy(str, Enum):
    """Order fill policy for partial fills."""

    FOK = "FOK"
    """Fill or Kill - entire order or nothing."""

    IOC = "IOC"
    """Immediate or Cancel - execute any partial fill."""

    RETURN = "RETURN"
    """Return - return unexecuted volume (market conditions dependent)."""

    POLICY = "POLICY"
    """Use account policy setting."""


class RiskState(str, Enum):
    """System risk state classification."""

    NORMAL = "NORMAL"
    """All systems nominal, trading permitted."""

    CAUTION = "CAUTION"
    """Elevated risk detected, reduced position sizing."""

    RISK_OFF = "RISK_OFF"
    """High risk, no new positions, close at first opportunity."""

    HALT = "HALT"
    """Critical risk, all trading halted, close all positions."""


class SignalDirection(str, Enum):
    """Trading signal direction."""

    LONG = "LONG"
    """Signal indicates bullish direction."""

    SHORT = "SHORT"
    """Signal indicates bearish direction."""

    FLAT = "FLAT"
    """Signal indicates neutral/no position."""


class ChallengeType(str, Enum):
    """FTMO challenge phase."""

    ONE_STEP = "ONE_STEP"
    """Single verification step."""

    TWO_STEP = "TWO_STEP"
    """Two-stage verification process."""


class ExecutionStatus(str, Enum):
    """Status of order execution attempt."""

    PENDING = "PENDING"
    """Order submitted, awaiting execution."""

    EXECUTED = "EXECUTED"
    """Order fully executed."""

    PARTIAL = "PARTIAL"
    """Order partially filled."""

    REJECTED = "REJECTED"
    """Order rejected by broker."""

    CANCELLED = "CANCELLED"
    """Order cancelled."""

    TIMEOUT = "TIMEOUT"
    """Execution attempt timed out."""


