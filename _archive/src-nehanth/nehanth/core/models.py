class TradingSignal(BaseModel):
    """Represents a trading signal generated by a strategy.

    A signal indicates a trading opportunity with confidence score
    and metadata for audit and correlation.
    """

    model_config = ConfigDict(frozen=True)

    signal_id: UUID = Field(default_factory=uuid4, description="Unique signal identifier.")
    symbol: str = Field(..., min_length=1, max_length=10, description="Trading instrument symbol.")
    direction: SignalDirection = Field(..., description="Long, short, or flat direction.")
    confidence: Decimal = Field(
        ...,
        ge=Decimal("0"),
        le=Decimal("1"),
        description="Confidence level 0-1.",
    )
    timestamp: datetime = Field(..., description="Signal generation time (UTC, timezone-aware).")
    correlation_id: UUID = Field(..., description="Correlation ID for tracing.")
    meta_label_prob: Optional[Decimal] = Field(
        default=None,
        ge=Decimal("0"),
        le=Decimal("1"),
        description="ML probability from meta-labeling.",
    )
    strategy_name: str = Field(..., min_length=1, description="Name of generating strategy.")

    @field_validator("confidence", "meta_label_prob", mode="before")
    @classmethod
    def convert_to_decimal(cls, v: Any) -> Optional[Decimal]:
        """Ensure confidence values are Decimal."""
        if v is None:
            return None
        if isinstance(v, Decimal):
            return v
        return Decimal(str(v))


class TradeRequest(BaseModel):
    """Represents a request to execute a trade.

    Contains all necessary parameters for order submission to MT5.
    """

    model_config = ConfigDict(frozen=True)

    symbol: str = Field(..., min_length=1, max_length=10, description="Trading instrument.")
    action: OrderAction = Field(..., description="Buy/sell/close action.")
    order_type: OrderType = Field(..., description="Market/limit/stop order type.")
    volume: Decimal = Field(..., gt=Decimal("0"), description="Order size (lots).")
    price: Optional[Decimal] = Field(
        default=None,
        gt=Decimal("0"),
        description="Limit/stop price for non-market orders.",
    )
    sl: Optional[Decimal] = Field(
        default=None,
        gt=Decimal("0"),
        description="Stop loss price.",
    )
    tp: Optional[Decimal] = Field(
        default=None,
        gt=Decimal("0"),
        description="Take profit price.",
    )
    deviation: Optional[int] = Field(
        default=None,
        ge=0,
        description="Price deviation tolerance in points.",
    )
    magic: int = Field(..., ge=0, description="Order magic number for identification.")
    comment: str = Field(
        default="",
        max_length=27,
        description="MT5 order comment (max 27 chars).",
    )
    fill_policy: FillPolicy = Field(default=FillPolicy.POLICY, description="Fill policy for partial fills.")
    correlation_id: UUID = Field(..., description="Correlation ID for tracing.")

    @field_validator("volume", "price", "sl", "tp", mode="before")
    @classmethod
    def convert_to_decimal(cls, v: Any) -> Optional[Decimal]:
        """Ensure numeric financial fields are Decimal."""
        if v is None:
            return None
        if isinstance(v, Decimal):
            return v
        return Decimal(str(v))


